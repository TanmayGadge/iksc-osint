from langgraph.graph import StateGraph, START, END
from langgraph.prebuilt import ToolNode
from langgraph.graph.message import add_messages

from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.messages import BaseMessage, HumanMessage, SystemMessage, AIMessage

from typing import TypedDict, Annotated, cast
from pydantic import BaseModel, Field

from dotenv import load_dotenv
load_dotenv()

class AgentState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]

class OutputFormat(BaseModel):
    type: str = Field(description="The type of the joke generated")
    joke: str = Field(description="The joke generated by the model")


def joke_agent(state:AgentState):
    model = ChatGoogleGenerativeAI(model='gemini-2.5-flash-lite', temperature=0.9)
    structured_model = model.with_structured_output(OutputFormat)
    
    resp = cast(OutputFormat, structured_model.invoke(state['messages']))
    ai_msg = AIMessage(content=resp.model_dump_json())
    return {"messages": [ai_msg]}


graph = StateGraph(AgentState)
graph.add_node('agent', joke_agent)
graph.add_edge(START, "agent")
graph.add_edge('agent', END)


initial_input: AgentState ={
    "messages": [
        SystemMessage(content="Act as a professional comedian and generate jokes about the topic mentioned by the user"),
        HumanMessage(
            content="Give me a joke about chickens"
        ) 
    ]
}

app = graph.compile()
for event in app.stream(initial_input, stream_mode='values'):
    print(event)
    
